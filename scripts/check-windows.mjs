#!/usr/bin/env node
// check-windows.mjs — compile and lint the engine for Windows on Linux.
//
// Why this exists: `#[cfg(windows)]` code is not compiled by a normal Linux
// build, so `cargo clippy` on Linux cannot see that a Windows-only item is
// dead, or that a Windows-only import became unnecessary. Those failures used
// to surface only on the windows-latest CI job, minutes after a push — and
// every red run costs Actions minutes.
//
// This runs the real compiler for the Windows target, so the answer is exact
// rather than a heuristic over `#[cfg]` attributes:
//
//   cargo clippy --workspace --all-targets --target x86_64-pc-windows-gnu -D warnings
//
// `ring` (via rustls/reqwest) ships C code, so a C compiler for the target is
// required; zig provides one without a toolchain install or root access. The
// script generates the small `cc`/`c++` shims that translate the Rust target
// triple into the one zig's driver accepts.
//
// Requirements: zig on PATH (or BEBOK_ZIG=/path/to/zig) and the rustup target
// `x86_64-pc-windows-gnu` (added automatically when rustup is available).
//
//   node scripts/check-windows.mjs [--check|--clippy]   (default: --clippy)

import { mkdtempSync, writeFileSync, chmodSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(new URL('..', import.meta.url)));
const ENGINE = join(ROOT, 'engine');
const TARGET = 'x86_64-pc-windows-gnu';
const ZIG_TARGET = 'x86_64-windows-gnu';
const mode = process.argv.includes('--check') ? 'check' : 'clippy';

function fail(message, hint) {
  console.error(`✗ ${message}`);
  if (hint) console.error(`  ${hint}`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// zig
// ---------------------------------------------------------------------------

function findZig() {
  const explicit = process.env.BEBOK_ZIG;
  const candidates = explicit ? [explicit] : ['zig'];
  for (const candidate of candidates) {
    const probe = spawnSync(candidate, ['version'], { encoding: 'utf8' });
    if (!probe.error && probe.status === 0) return candidate;
  }
  return null;
}

const zig = findZig();
if (!zig) {
  fail(
    'zig not found.',
    'Install it (no root needed): download the tarball from https://ziglang.org/download/, ' +
      'untar anywhere, and either put `zig` on PATH or set BEBOK_ZIG=/path/to/zig.',
  );
}

// ---------------------------------------------------------------------------
// rustup target
// ---------------------------------------------------------------------------

const installed = spawnSync('rustup', ['target', 'list', '--installed'], { encoding: 'utf8' });
if (!installed.error && !(installed.stdout || '').includes(TARGET)) {
  console.log(`· installing rustup target ${TARGET}`);
  const add = spawnSync('rustup', ['target', 'add', TARGET], { stdio: 'inherit' });
  if (add.status !== 0) fail(`could not add the ${TARGET} target`);
}

// ---------------------------------------------------------------------------
// cc / c++ shims
// ---------------------------------------------------------------------------
//
// cc-rs passes `--target=x86_64-pc-windows-gnu`, which zig's driver rejects; it
// wants `x86_64-windows-gnu`. The shims rewrite just that argument and leave
// everything else untouched (quoted, so paths with spaces survive).

const shimDir = mkdtempSync(join(tmpdir(), 'bebok-zigcc-'));

function shim(name, driver) {
  const path = join(shimDir, name);
  const body = `#!/bin/sh
# Generated by scripts/check-windows.mjs — rewrites the Rust target triple to
# the spelling zig's driver accepts, then delegates.
out=""
for a in "$@"; do
  case "$a" in
    --target=${TARGET}|--target=${TARGET}*) out="$out -target ${ZIG_TARGET}" ;;
    *) out="$out $(printf '%s' "$a" | sed 's/[[:space:]]/\\\\ /g')" ;;
  esac
done
eval exec "${driver}" $out
`;
  writeFileSync(path, body);
  chmodSync(path, 0o755);
  return path;
}

const cc = shim('cc', `${zig} cc`);
const cxx = shim('c++', `${zig} c++`);

const env = {
  ...process.env,
  [`CC_${TARGET}`]: cc,
  [`CXX_${TARGET}`]: cxx,
  [`AR_${TARGET}`]: `${zig} ar`,
};

// ---------------------------------------------------------------------------
// run
// ---------------------------------------------------------------------------

const args =
  mode === 'check'
    ? ['check', '--workspace', '--all-targets', '--target', TARGET]
    : ['clippy', '--workspace', '--all-targets', '--target', TARGET, '--', '-D', 'warnings'];

console.log(`· cargo ${args.join(' ')}`);
const run = spawnSync('cargo', args, { cwd: ENGINE, env, stdio: 'inherit' });

rmSync(shimDir, { recursive: true, force: true });

if (run.error) fail(`cargo could not run: ${run.error.message}`);
if (run.status !== 0) {
  fail(
    `Windows ${mode} failed — this is what the windows-latest CI job would report.`,
    'The errors above are real: the same code does not compile or lint on Windows.',
  );
}
console.log(`✓ Windows ${mode} clean (${TARGET})`);
